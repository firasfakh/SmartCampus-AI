-- SmartCampus AI — SA-12 academic catalog schema.
-- Unquoted PostgreSQL identifiers are stored in lowercase; names correspond
-- to the 11 logical tables in the approved MLD.

BEGIN;

CREATE TABLE academic_institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    institution_code VARCHAR(30) NOT NULL,
    institution_name VARCHAR(255) NOT NULL,
    CONSTRAINT pk_academic_institutions PRIMARY KEY (id),
    CONSTRAINT uq_academic_institutions_institution_code UNIQUE (institution_code)
);

CREATE TABLE academic_programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    institution_id BIGINT NOT NULL,
    program_code VARCHAR(50) NOT NULL,
    program_name VARCHAR(255) NOT NULL,
    program_type VARCHAR(50) NOT NULL,
    program_domain VARCHAR(100),
    teaching_language VARCHAR(50),
    program_duration VARCHAR(100),
    total_credits INTEGER,
    program_description TEXT,
    CONSTRAINT pk_academic_programs PRIMARY KEY (id),
    CONSTRAINT uq_academic_programs_program_code UNIQUE (program_code),
    CONSTRAINT ck_academic_programs_total_credits_nonnegative
        CHECK (total_credits >= 0),
    CONSTRAINT fk_academic_programs_institution
        FOREIGN KEY (institution_id)
        REFERENCES academic_institutions (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE specializations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    program_id BIGINT NOT NULL,
    specialization_name VARCHAR(255) NOT NULL,
    specialization_description TEXT,
    CONSTRAINT pk_specializations PRIMARY KEY (id),
    CONSTRAINT fk_specializations_program
        FOREIGN KEY (program_id)
        REFERENCES academic_programs (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE curricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    program_id BIGINT NOT NULL,
    curriculum_academic_year VARCHAR(20),
    CONSTRAINT pk_curricula PRIMARY KEY (id),
    CONSTRAINT uq_curricula_program_academic_year
        UNIQUE NULLS NOT DISTINCT (program_id, curriculum_academic_year),
    CONSTRAINT fk_curricula_program
        FOREIGN KEY (program_id)
        REFERENCES academic_programs (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE semesters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    curriculum_id BIGINT NOT NULL,
    semester_number INTEGER NOT NULL,
    semester_label VARCHAR(100),
    CONSTRAINT pk_semesters PRIMARY KEY (id),
    CONSTRAINT uq_semesters_curriculum_semester_number
        UNIQUE (curriculum_id, semester_number),
    CONSTRAINT ck_semesters_semester_number_positive
        CHECK (semester_number >= 1),
    CONSTRAINT fk_semesters_curriculum
        FOREIGN KEY (curriculum_id)
        REFERENCES curricula (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    semester_id BIGINT NOT NULL,
    module_name VARCHAR(255) NOT NULL,
    module_description TEXT,
    CONSTRAINT pk_modules PRIMARY KEY (id),
    CONSTRAINT fk_modules_semester
        FOREIGN KEY (semester_id)
        REFERENCES semesters (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    module_id BIGINT NOT NULL,
    subject_name VARCHAR(255) NOT NULL,
    subject_credits NUMERIC(5, 2),
    subject_coefficient NUMERIC(6, 3),
    lecture_hours NUMERIC(7, 2),
    practical_hours NUMERIC(7, 2),
    lab_hours NUMERIC(7, 2),
    CONSTRAINT pk_subjects PRIMARY KEY (id),
    CONSTRAINT ck_subjects_credits_nonnegative
        CHECK (subject_credits >= 0),
    CONSTRAINT ck_subjects_coefficient_positive
        CHECK (subject_coefficient > 0),
    CONSTRAINT ck_subjects_lecture_hours_nonnegative
        CHECK (lecture_hours >= 0),
    CONSTRAINT ck_subjects_practical_hours_nonnegative
        CHECK (practical_hours >= 0),
    CONSTRAINT ck_subjects_lab_hours_nonnegative
        CHECK (lab_hours >= 0),
    CONSTRAINT fk_subjects_module
        FOREIGN KEY (module_id)
        REFERENCES modules (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE admission_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    program_id BIGINT NOT NULL,
    required_diploma TEXT,
    admission_process TEXT,
    required_documents TEXT,
    additional_conditions TEXT,
    CONSTRAINT pk_admission_requirements PRIMARY KEY (id),
    CONSTRAINT ck_admission_requirements_has_content
        CHECK (
            required_diploma IS NOT NULL
            OR admission_process IS NOT NULL
            OR required_documents IS NOT NULL
            OR additional_conditions IS NOT NULL
        ),
    CONSTRAINT fk_admission_requirements_program
        FOREIGN KEY (program_id)
        REFERENCES academic_programs (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE program_fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    program_id BIGINT NOT NULL,
    fee_category VARCHAR(100) NOT NULL,
    fee_amount NUMERIC(12, 3),
    fee_currency VARCHAR(10),
    fee_period VARCHAR(50),
    fee_academic_year VARCHAR(20),
    fee_status VARCHAR(30),
    fee_notes TEXT,
    CONSTRAINT pk_program_fees PRIMARY KEY (id),
    CONSTRAINT ck_program_fees_amount_nonnegative
        CHECK (fee_amount >= 0),
    CONSTRAINT ck_program_fees_currency_required_for_amount
        CHECK (
            fee_amount IS NULL
            OR (fee_currency IS NOT NULL AND fee_currency ~ '^[A-Z]{3}$')
        ),
    CONSTRAINT fk_program_fees_program
        FOREIGN KEY (program_id)
        REFERENCES academic_programs (id)
        ON DELETE RESTRICT
        ON UPDATE NO ACTION
);

CREATE TABLE career_opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    career_job_title VARCHAR(255) NOT NULL,
    career_industry VARCHAR(255),
    career_description TEXT,
    CONSTRAINT pk_career_opportunities PRIMARY KEY (id)
);

CREATE TABLE program_careers (
    program_id BIGINT NOT NULL,
    career_id BIGINT NOT NULL,
    CONSTRAINT pk_program_careers PRIMARY KEY (program_id, career_id),
    CONSTRAINT fk_program_careers_program
        FOREIGN KEY (program_id)
        REFERENCES academic_programs (id)
        ON DELETE CASCADE
        ON UPDATE NO ACTION,
    CONSTRAINT fk_program_careers_career
        FOREIGN KEY (career_id)
        REFERENCES career_opportunities (id)
        ON DELETE CASCADE
        ON UPDATE NO ACTION
);

CREATE INDEX ix_academic_programs_institution_id
    ON academic_programs (institution_id);
CREATE INDEX ix_specializations_program_id
    ON specializations (program_id);
CREATE INDEX ix_modules_semester_id
    ON modules (semester_id);
CREATE INDEX ix_subjects_module_id
    ON subjects (module_id);
CREATE INDEX ix_admission_requirements_program_id
    ON admission_requirements (program_id);
CREATE INDEX ix_program_fees_program_id
    ON program_fees (program_id);
CREATE INDEX ix_program_careers_career_id
    ON program_careers (career_id);

COMMIT;
